"""WireGuard client configuration that routes an agent's traffic to the gateway.

WireGuard decides where a packet goes by the peer's ``AllowedIPs``. Pointing
``0.0.0.0/0, ::/0`` at the gateway is a full tunnel: every connection the agent
opens leaves through the gateway's host, where the egress firewall sends it to
``vaara net-gate`` and nowhere else. Split tunnelling is the same list with the
directly-allowed ranges cut out of it: those ranges go straight out, everything
else is forced through the gateway.

WireGuard has no "everything except" syntax, so the cut is computed here: the
complement of the direct ranges as the smallest set of CIDR blocks.

This module writes the client side only. Keys are generated by ``wg genkey``
on the agent's host and never pass through Vaara; the private key field is left
as a placeholder for that reason.
"""

from __future__ import annotations

import ipaddress
from typing import Iterable, Union

_Net = Union[ipaddress.IPv4Network, ipaddress.IPv6Network]

_ALL = (ipaddress.ip_network("0.0.0.0/0"), ipaddress.ip_network("::/0"))


def split_allowed_ips(direct: Iterable[str]) -> list[str]:
    """AllowedIPs that send everything through the tunnel except ``direct``.

    ``direct`` are CIDRs or single addresses that should bypass the gateway.
    An empty ``direct`` returns the full tunnel. The result is sorted, IPv4
    first, and collapsed, so it is stable to diff and minimal to read.
    """
    cuts = [ipaddress.ip_network(d.strip(), strict=False) for d in direct if d.strip()]
    out: list[_Net] = []
    for whole in _ALL:
        remaining = [whole]
        for cut in cuts:
            if cut.version != whole.version:
                continue
            nxt: list[_Net] = []
            for block in remaining:
                if cut == block or block.subnet_of(cut):  # type: ignore[arg-type]
                    continue
                if cut.subnet_of(block):  # type: ignore[arg-type]
                    nxt.extend(block.address_exclude(cut))  # type: ignore[arg-type]
                else:
                    nxt.append(block)
            remaining = nxt
        out.extend(ipaddress.collapse_addresses(remaining))  # type: ignore[arg-type,type-var]
    return [str(n) for n in sorted(out, key=lambda n: (n.version, n))]


def client_config(*, address: str, gateway_public_key: str, endpoint: str,
                  direct: Iterable[str] = (), dns: str = "",
                  keepalive: int = 25) -> str:
    """A wg-quick config for the agent's host."""
    lines = [
        "# Written by vaara net-gate. Routes this agent's traffic through the",
        "# Vaara gateway; only the ranges cut out of AllowedIPs go direct.",
        "[Interface]",
        "PrivateKey = <output of `wg genkey` on this host>",
        f"Address = {address}",
    ]
    if dns:
        lines.append(f"DNS = {dns}")
    lines += [
        "",
        "[Peer]",
        f"PublicKey = {gateway_public_key}",
        f"Endpoint = {endpoint}",
        f"AllowedIPs = {', '.join(split_allowed_ips(direct))}",
        f"PersistentKeepalive = {keepalive}",
    ]
    return "\n".join(lines) + "\n"
